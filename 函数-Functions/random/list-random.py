# 从列表里随机获取元素

import random

list1 = [99, 89, 34, 8, 20, 100, 1008, 45]

random_element = random.choice(list1)

print(random_element)


list2 = ['a', 'b', 'c', 'd']

random_letter = random.choice(list2)

print(random_letter)


list3 = ['jim', 'kate', 'lily', 'carol', 'sphoie']

random_name = random.choice(list3)

print(random_name)

