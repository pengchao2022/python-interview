# split() 函数对字符串进行分割

sentence = "Michael learns to rock"

words = sentence.split()       # 以空格分隔 生成一个列表

print(words)

fruits = "apple, banana, orange, pear, grape"

my_fruit = fruits.split(",")   # 以逗号分隔 生成一个列表

print(my_fruit)

# 输出结果为：['Michael', 'learns', 'to', 'rock']
# 输出结果为：['apple', ' banana', ' orange', ' pear', ' grape']

