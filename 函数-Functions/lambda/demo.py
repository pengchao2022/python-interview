# lambda 函数实现两个数相加

func = lambda x, y: x + y

result = func(8, 9)

print(result)


# lambda 函数实现两个数相减

func = lambda x, y: x - y

result = func(9, 4)

print(result)


# lambda 函数实现两个数相乘

func = lambda x, y: x * y

result = func(8, 9)

print(result)


# lambda 函数实现两个数相除

func = lambda x, y: x / y

result = func(9, 3)

print(result)

